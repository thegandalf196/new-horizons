{
	return COLORS;
}

Body makeBody(Direction direction)
{
	const auto index = static_cast<size_t>(direction);
	if(index >= FRAMES.size())
		throw std::invalid_argument("Invalid Reach cursor direction");
	Body result;
	result.hotspot = TIPS[index];
	result.inkTopLeft = {Body::SIZE, Body::SIZE};
	for(int y = 0; y < Body::SIZE; ++y)
		for(int x = 0; x < Body::SIZE; ++x)
		{
			const char pixel = FRAMES[index][y][x];
			const auto color = pixel == '.' ? 0 : pixel == 'A' ? 10 : pixel - '0';
			result.pixels[y * Body::SIZE + x] = static_cast<uint8_t>(color);
			if(!color)
				continue;
			result.inkTopLeft.x = std::min(result.inkTopLeft.x, x);
			result.inkTopLeft.y = std::min(result.inkTopLeft.y, y);
			result.inkBottomRight.x = std::max(result.inkBottomRight.x, x + 1);
			result.inkBottomRight.y = std::max(result.inkBottomRight.y, y + 1);
		}
	return result;
}
