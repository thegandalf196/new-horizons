"""Generate curated module metadata from canonical settings; --check detects drift."""
import argparse
import json
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = Path(__file__).resolve().parents[1]
    settings = json.loads((root / 'config/newHorizonsCombat.json').read_text(encoding='utf-8'))
    metadata = {
        'name': 'New Horizons',
        'description': 'Curated combat ruleset 1: three Orders and two battle-persistent Doctrines. '
                       'Provisional coefficients; balance is deferred. New games snapshot rules; '
                       'legacy saves retain their original semantics. Generated by '
                       'tools/update-new-horizons-module.py from config/newHorizonsCombat.json.',
        'modType': 'Mechanics',
        'version': '0.1.0',
        'author': 'New Horizons contributors',
        'licenseName': 'GPL-2.0-or-later; original artwork CC0-1.0',
        'licenseURL': 'https://www.gnu.org/licenses/old-licenses/gpl-2.0.html',
        'depends': ['vcmi'],
        'keepDisabled': False,
        # Named-file settings use the module's own filesystem, not core's config.
        # Inline generated settings preserve one authoring source without changing
        # that isolation or relying on an unmounted core file reference.
        'settings': settings,
        'filesystem': {'SPRITES/': [{'type': 'dir', 'path': '/Images'}]},
    }
    destination = root / 'Mods/new-horizons/mod.json'
    expected = json.dumps(metadata, indent='\t', ensure_ascii=False) + '\n'
    if args.check:
        if not destination.is_file() or destination.read_text(encoding='utf-8') != expected:
            parser.exit(1, 'Curated module metadata is stale; run tools/update-new-horizons-module.py\n')
        print('PASS: module settings equal canonical combat rules; image mount and metadata match')
    else:
        destination.parent.mkdir(parents=True, exist_ok=True)
        destination.write_text(expected, encoding='utf-8')
        print('Updated Mods/new-horizons/mod.json')


if __name__ == '__main__':
    main()
